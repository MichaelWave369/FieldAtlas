import { DOCUMENTED_CONNECTIONS } from './documented-connections.js';
import { CONNECTION_KINDS, validateDocumentedConnection } from './provenance-connections.js';
import { CONSTELLATION_URL } from './constellation-bridge.js';

const OWNER = 'MichaelWave369';
const NAME_RE = /^(?!\.{1,2}$)[A-Za-z0-9._-]{1,100}$/;
const SHA_RE = /^[a-f0-9]{40}$/i;

export function isDossierName(value) {
  return typeof value === 'string' && NAME_RE.test(value);
}
function iso(value) {
  if (typeof value !== 'string') return null;
  const timestamp = Date.parse(value);
  return Number.isFinite(timestamp) ? new Date(timestamp).toISOString() : null;
}
function validRecord(item) {
  return Boolean(item && item.isPublic === true && isDossierName(item.repo) &&
    Number.isSafeInteger(item.id) && item.id > 0);
}
function normalizeMilestones(items) {
  if (!Array.isArray(items)) return [];
  const used = new Set();
  return items.filter(m => m?.kind === 'merged-pr' &&
    Number.isSafeInteger(m.number) && m.number > 0 && iso(m.date) &&
    !used.has(m.number) && used.add(m.number))
    .slice(0,4).map(m => ({
      kind:'merged-pr', number:m.number,
      title:String(m.title || 'Untitled merged pull request').slice(0,140),
      date:iso(m.date),
      commit:SHA_RE.test(m.commit || '') ? m.commit.toLowerCase() : null,
    }));
}

/**
 * Render only the public-owner snapshot generated by the deployment.
 * It is NOT a manifest of playable published Pages and grants no iframe access.
 */
export function parseEncyclopediaSnapshot(payload) {
  if (!payload || payload.schema_version !== 1 || payload.owner !== OWNER ||
    !Array.isArray(payload.repositories)) throw new Error('Unexpected public encyclopedia format');
  const seen = new Set(), ids = new Set(), repositories = [];
  for (const item of payload.repositories) {
    if (!validRecord(item)) continue;
    const key = item.repo.toLowerCase();
    if (seen.has(key) || ids.has(item.id)) continue;
    seen.add(key); ids.add(item.id);
    repositories.push({
      id:item.id, repo:item.repo,
      description:typeof item.description === 'string' ? item.description.slice(0,300) : '',
      language:typeof item.language === 'string' ? item.language.slice(0,40) : null,
      createdAt:iso(item.createdAt), pushedAt:iso(item.pushedAt),
      archived:item.archived === true, fork:item.fork === true, isPublic:true,
      historyStatus:item.historyStatus === 'checked' ? 'checked' : 'unavailable',
      milestones:normalizeMilestones(item.milestones),
      sourceUrl:'https://github.com/' + OWNER + '/' + encodeURIComponent(item.repo),
    });
  }
  repositories.sort((a,b) => a.repo.localeCompare(b.repo,'en',{sensitivity:'base'}));
  return {
    repositories,
    generatedAt:iso(payload.generated_at),
    complete:payload.complete === true,
  };
}

export function readDossierQuery(search = '') {
  const params = new URLSearchParams(String(search).replace(/^\?/, ''));
  const values = params.getAll('dossier');
  return values.length === 1 && isDossierName(values[0]) ? values[0] : null;
}

export function findDossier(repositories, repo) {
  if (!Array.isArray(repositories) || !isDossierName(repo)) return null;
  const matching = repositories.filter(record => validRecord(record) &&
    record.repo.toLowerCase() === repo.toLowerCase());
  return matching.length === 1 ? matching[0] : null;
}

export function dossierShareUrl(href, repo) {
  if (!isDossierName(repo)) return null;
  const url = new URL(href);
  if (!['http:','https:'].includes(url.protocol)) return null;
  for (const param of ['chapter','tour','project','dossier']) url.searchParams.delete(param);
  url.searchParams.set('dossier',repo);
  url.hash = 'living-encyclopedia';
  return url.href;
}

export function dossierConstellationUrl(record) {
  if (!validRecord(record)) return null;
  const url = new URL(CONSTELLATION_URL);
  url.searchParams.set('repo','github:' + record.id);
  return url.href;
}

/**
 * Only real merged public PRs or GitHub repo timestamps are treated as history.
 * A push is an observation, NOT verification of a release, deployment or feature.
 */
export function dossierTimeline(record) {
  if (!validRecord(record)) return [];
  const events = [];
  if (record.createdAt) events.push({
    id:'created',date:record.createdAt,label:'Repository created',detail:'Public GitHub repository creation timestamp',
    url:record.sourceUrl,
  });
  if (record.pushedAt) events.push({
    id:'pushed',date:record.pushedAt,label:'Latest push observed',detail:'Repository pushed_at, not evidence of a released feature',
    url:record.sourceUrl,
  });
  for (const event of record.milestones || []) {
    if (event.kind !== 'merged-pr' || !Number.isSafeInteger(event.number) || !iso(event.date)) continue;
    events.push({
      id:'pr-' + event.number,date:event.date,label:'Merged PR #' + event.number,
      detail:event.title,
      url:record.sourceUrl + '/pull/' + event.number,
      commit:event.commit,
    });
  }
  return events.sort((a,b)=> Date.parse(b.date)-Date.parse(a.date) || a.id.localeCompare(b.id));
}

/**
 * Existing citation-pinned ledger, never inferred from common words or project
 * titles. Two owner-public dossier endpoints are required for every edge.
 */
export function dossierConnections(record, repositories = [], ledger = DOCUMENTED_CONNECTIONS) {
  if (!validRecord(record) || !Array.isArray(repositories) || !Array.isArray(ledger) ||
    !findDossier(repositories,record.repo)) return [];
  const result = [], seen = new Set();
  for (const edge of ledger) {
    if (!validateDocumentedConnection(edge) || seen.has(edge.id)) continue;
    const from = findDossier(repositories,edge.fromRepo);
    const to = findDossier(repositories,edge.toRepo);
    if (!from || !to) continue;
    const outbound = from.repo.toLowerCase() === record.repo.toLowerCase();
    const inbound = to.repo.toLowerCase() === record.repo.toLowerCase();
    if (!outbound && !inbound) continue;
    seen.add(edge.id);
    result.push({
      id:edge.id, other:outbound ? to : from,
      direction:outbound ? 'outbound' : 'inbound',
      label:CONNECTION_KINDS[edge.kind], summary:edge.summary,
      scope:edge.scope,evidenceUrl:edge.evidenceUrl,
    });
  }
  return result;
}
